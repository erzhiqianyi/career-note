// Renders the deploy-time Wrangler config from the generic wrangler.toml.
// The committed file carries no hostname or database id so forks can use it unchanged; the values that
// belong to one Cloudflare account are supplied here and written to a gitignored wrangler.deploy.toml.
//   CAREER_API_HOST  public hostname of the API Worker, e.g. career-api.example.com (required)
//   CAREER_D1_NAME   D1 database name (default: career-note)
//   CAREER_D1_ID     D1 database id; when unset it is looked up by name with `wrangler d1 list` (needs Cloudflare credentials)
//   argv[2]          output path (default: wrangler.deploy.toml)
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
const host=(process.env.CAREER_API_HOST||'').trim().replace(/^https?:\/\//,'').replace(/\/.*$/,'');
if(!host){console.error('CAREER_API_HOST is required (e.g. career-api.example.com).');process.exit(1);}
const dbName=(process.env.CAREER_D1_NAME||'career-note').trim();
let dbId=(process.env.CAREER_D1_ID||'').trim();
if(!dbId){
 // `d1 list`, not `d1 info <name>`: info resolves a name through the bindings in wrangler.toml and would query the placeholder id.
 const out=execFileSync('node',['node_modules/wrangler/bin/wrangler.js','d1','list','--json'],{encoding:'utf8',stdio:['ignore','pipe','inherit']});
 dbId=(JSON.parse(out.slice(out.indexOf('['))).find(db=>db.name===dbName)||{}).uuid||'';
 if(!dbId){console.error(`Could not resolve the id of D1 database "${dbName}"; create it with \`wrangler d1 create ${dbName}\` or set CAREER_D1_ID.`);process.exit(1);}
}
const output=process.argv[2]||'wrangler.deploy.toml';
let toml=readFileSync('wrangler.toml','utf8');
const replace=(regex,line,label)=>{if(!regex.test(toml)){console.error(`wrangler.toml: ${label} not found`);process.exit(1);}toml=toml.replace(regex,line);};
replace(/^database_name\s*=.*$/m,`database_name = "${dbName}"`,'database_name');
replace(/^database_id\s*=.*$/m,`database_id = "${dbId}"`,'database_id');
replace(/^(compatibility_flags\s*=.*)$/m,`$1\n\n# Generated by scripts/render-wrangler-config.mjs; do not commit.\nroutes = [{ pattern = "${host}", custom_domain = true }]`,'compatibility_flags');
writeFileSync(output,toml);
console.log(`Wrote ${output}: route ${host}, D1 ${dbName} (${dbId}).`);
